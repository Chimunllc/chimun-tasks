-- public_availability — mevent.mn-д НӨӨЦ ЭЗЭЛЖ БАЙГАА захиалгыг гаргах харагдац
-- Сүүлд шинэчилсэн: 2026-09-10
--
-- ЮУНД ХЭРЭГТЭЙ
--   Сайт «тухайн өдөр хэдэн ширхэг сул байна» гэдгийг бодохын тулд идэвхтэй
--   түрээсийг мэдэх ёстой. Гэхдээ `app_orders` хүснэгтийг нийтэд нээж болохгүй —
--   тэнд харилцагчийн нэр, утас, и-мэйл, хаяг, төлбөр байдаг (1000+ мөр).
--   Тиймээс харагдац зөвхөн 4 зүйл гаргана: захиалгын дугаар, эхлэх/дуусах огноо,
--   барааны sku/нэр/тоо.
--
-- ⚠ ХАМГИЙН ЧУХАЛ: доорх төлвийн жагсаалт аппын `_ORDER_OCCUPYING`-тэй
--    (app.js) ЯГ ИЖИЛ байх ёстой. Зөрвөл апп ба сайт ӨӨР сул үлдэгдэл харуулж,
--    давхар захиалга үүснэ. Аль нэгийг өөрчлөх = хоёуланг ЗЭРЭГ өөрчлөх.
--    `test/run.js`-д SCAN-тест бий — хоёр жагсаалт зөрвөл CI унана.
--
-- ⚠ `installing` (хүргэсэн, суурилуулж байгаа) ба `teardown` (буулгасан, агуулахад
--    ирээгүй) 2026-09-10 хүртэл ОРООГҮЙ байсан. Ачаа үйлчлүүлэгчийн талбай дээр
--    байхад апп ч, сайт ч тэр барааг «бүрэн чөлөөт» гэж харуулж, тэр өдөр өөр
--    захиалга авах боломжтой байв. Суурилуулалттай захиалга бүрд 2 цонх нээгддэг.
--    Асар/тайз/хөгжим яг энэ урсгалаар явдаг — нэг давхцал 3-5 сая₮.
--
-- ⚠ Эзнийхээ эрхээр ажиллана (`security_invoker` тавиагүй) тул `app_orders`
--    нийтэд хаалттай байсан ч энэ харагдац ажиллана.
-- ═══════════════════════════════════════════════════════════════════════

begin;

create or replace view public.public_availability as
  select number,
         starts_at,
         stops_at,
         coalesce((
           select jsonb_agg(jsonb_build_object(
                    'sku',  it.value ->> 'sku',
                    'name', it.value ->> 'name',
                    'qty',  it.value ->> 'qty'))
           from jsonb_array_elements(coalesce(o.items, '[]'::jsonb)) it(value)
         ), '[]'::jsonb) as items
  from public.app_orders o
  where status = any (array[
    'reserved',      -- төлбөр төлөгдсөн, хүлээгдэж байгаа
    'preparation',
    'cleaning',
    'ready',
    'started',
    'prepared',
    'delivering',    -- агуулахаас гарсан
    'installing',    -- хүргэсэн, суурилуулж байгаа
    'rented',        -- үйлчлүүлэгч дээр
    'teardown',      -- буулгасан, агуулахад ирээгүй
    'returning'      -- буцаж явж байгаа
  ])
  -- ⚠ САЙТААС ИРСЭН НООРОГ БАС НӨӨЦ ЭЗЭЛНЭ (2026-09-10).
  --   Сайтын захиалга ҮРГЭЛЖ `draft` төлөвтэй ирдэг (харилцагч онлайн төлдөггүй).
  --   Ноорог нөөц эздэггүй байсан тул сайт нэг барааг хязгааргүй олон удаа зарч
  --   чадаж байв — нэг зочин 10 сандал захиалсан ч дараагийнхад 10 сандал бүрэн
  --   сул харагдана.
  --   ДОТООД ноорог (ажилтны үнийн санал) нөөц ЭЗЛЭХГҮЙ — зориудынх, 100 сая₮-ийн
  --   санал нөөцийг блоклох ёсгүй. Ялгах хүчин зүйл = `source`.
  --   ⚠ Аппын `_ORDER_OCCUPYING_DRAFT_SOURCES`-тэй ЯГ ИЖИЛ байх ёстой
  --     (test/run.js хоёрыг тулгадаг).
     or (status = 'draft' and source = any (array['m-event-website'])
         -- ⚠ 72 цаг хүртэл л барина. Хугацаагүй барьвал нэг халдагч (эсвэл ирээгүй
         --    нэг харилцагч) каталогийг тодорхойгүй хугацаагаар блоклоно. Ямар ч
         --    үер 72 цагийн дараа өөрөө арилна. Аппын `_SITE_DRAFT_HOLD_H`-тэй
         --    ЯГ ИЖИЛ байх ёстой (test/run.js тулгана).
         and created_at > now() - interval '72 hours'
         -- Хэвийн бус захиалгыг n8n `Build Row` ⟦SUSPECT⟧ гэж тэмдэглэнэ —
         -- жагсаалтад харагдана, гэхдээ нөөц эзлэхгүй.
         and coalesce(note, '') not like '%⟦SUSPECT⟧%');

comment on view public.public_availability is
  'mevent.mn-д нөөц эзэлж байгаа захиалга. Төлвийн жагсаалт app.js-ийн _ORDER_OCCUPYING-тэй ЯГ ИЖИЛ байх ёстой (зөрвөл давхар захиалга үүснэ; test/run.js SCAN-тест хамгаална). Эх хувь: chimun-tasks/db/public_availability.sql';

grant select on public.public_availability to anon, authenticated;

commit;

notify pgrst, 'reload schema';

