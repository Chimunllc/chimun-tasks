-- Алдсан дуудлагыг буцаж залгасан тэмдэглэл (2026-09-16).
--
-- ЯАГААД: амьд датагаар 139 хүн залгаад холбогдоогүй, буцаж залгасан нь **0**.
-- Дуудлагын лог (`pbx_calls`) нь хэн залгасныг мэддэг ч «бид үүнийг шийдсэн үү»
-- гэдгийг мэддэггүй тул жагсаалт хэзээ ч богиносдоггүй, хэн юу барьсан нь ч
-- мэдэгдэхгүй байв.
--
-- ⚠ НЭГ ДУГААР = НЭГ МӨР. Түүх биш, ТӨЛӨВ хадгална.
-- ⚠ `upto` = «энэ цаг хүртэлх дуудлага нь шийдэгдсэн». Тэр хүн ДАХИН залгавал
--   шинэ дуудлагын цаг `upto`-оос хойш байх тул жагсаалтад ӨӨРӨӨ эргэж гарна.
--   Ингэснээр «бүрмөсөн хаах» товч хэрэггүй болж, дахин залгасан хүн алдагдахгүй.
-- ⛔ Хатуу устгал ОЛГОХГҮЙ (`db/rls.sql`-ийн ерөнхий дүрэм).
-- ⛔ anon-д ОГТ нээхгүй — дугаар нь хувийн мэдээлэл (`pbx_calls`-тай ижил).
create table if not exists pbx_callbacks (
  peer       text        primary key,          -- ГАДААД дугаар (pbx_calls.peer)
  status     text        not null default 'no_answer',  -- reached | no_answer | dropped
  tries      int         not null default 0,   -- бид хэдэн удаа буцаж залгасан
  note       text,
  by_key     text,                             -- хэн тэмдэглэсэн (personKey = утас)
  upto       timestamptz,                      -- аль дуудлага хүртэлх нь шийдэгдсэн
  updated_at timestamptz not null default now()
);

grant select, insert, update on pbx_callbacks to authenticated;
-- ⛔ DELETE-ийг ИЛ ХУРААНА. `chimun` эзний DEFAULT PRIVILEGES нь шинэ хүснэгт
--    бүрд `authenticated`-д `arwd` (устгах ч) АВТОМАТААР олгодог тул зөвхөн
--    grant бичээд орхивол хатуу устгал нээлттэй үлдэнэ (2026-09-16-нд амьд
--    туршилтаар DELETE 204 буцааж байсныг барьсан). `db/rls.sql` нь бүх
--    хүснэгтээс хураадаг ч тэр нь ДАХИН ажиллуулахад л хүчинтэй.
revoke delete on pbx_callbacks from authenticated;
