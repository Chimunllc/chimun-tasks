--   Дотроо зөрчилгүй ч тэр тоог ХЭН Ч биечлэн шалгаагүй — Booqable-аас,
--   гараас орж ирсэн. Иймд тооллого хийхэд гарах «зөрүү» нь юутай
--   харьцуулсан зөрүү нь тодорхойгүй. Тиймээс 19 тоололтын нэг нь ч
--   батлагдаагүй — хүн эргэлзсэн нь ЗӨВ.
--
--   Санхүүд яг ижил асуудлыг `closed_months.__cutover` -аар шийдсэн:
--   түүхийг тулгахгүй, огноо тавьж хаагаад цэвэр эхэлсэн. Нөөцөд мөн адил.
--
-- ⚠ ХАМГИЙН ЧУХАЛ ЗАН: тоолоод ТААРВАЛ ч тэмдэглэгдэнэ. Өмнө нь зөвхөн
--   ЗӨРҮҮ бүртгэгддэг байсан (`applyStockCount` нь diff=0 үед шууд гардаг)
--   тул «шалгасан бөгөөд зөв байсан» гэдэг мэдээлэл хаана ч үлддэггүй.
--   Суурь итгэл хүлээхгүй байсны гол шалтгаан яг энэ.
--
-- ГАРААР ажиллуулна. Идемпотент.
-- ═══════════════════════════════════════════════════════════════════════

alter table public.products add column if not exists stock_opened_at timestamptz;
alter table public.products add column if not exists stock_opened_by text;

comment on column public.products.stock_opened_at is
  'Нөөцийг биечлэн шалгаж баталгаажуулсан огноо (эхний үлдэгдэл). NULL = шалгаагүй.';

-- ⚠ anon-д НЭЭХГҮЙ — `products`-ийн нийтийн эрх БАГАНААР олгогддог тул
--   шинэ багана автоматаар нээгдэхгүй. Зөвхөн нэвтэрсэн ажилтанд.
grant select (stock_opened_at, stock_opened_by),
      insert (stock_opened_at, stock_opened_by),
      update (stock_opened_at, stock_opened_by)
  on public.products to authenticated;

notify pgrst, 'reload schema';

