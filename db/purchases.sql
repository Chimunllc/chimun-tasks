-- ХУДАЛДАН АВАЛТЫН ПРОЦЕСС = `purchases` (2026-10-26, CEO шийдвэр)
--
-- «Худалдан авалт» самбар өөрийн процесстой: хүсэлт → батлах → шилжүүлсэн →
-- худалдан авсан → хүлээн авсан (бараанд нэмэгдэнэ). Өмнө нь самбар зөвхөн
-- банкны хөрөнгийн зардлын мөрийг харуулдаг, бараа хэзээ ч бүртгэгддэггүй байв.
--
-- Нэг мөр = нэг нийлүүлэгчид өгөх НЭГ захиалга. Бараа бүрийн мөр `lines` дотор
-- (jsonb): { id, sku, name, q, c, s, b, u, cat, rcv, done }.
--   q = тоо · c = нэгж үнэ (fx=1 бол ₮, эс бөгөөс ¥) · s = хүргэлт+карго ₮
--   b = аль салбарт нэмэх · u = линк · rcv = хүлээн авсан тоо · done = үлдсэнийг хүлээхгүй
--
-- ⛔ ХҮЛЭЭН АВАЛТ = `stock_moves` ДЭВТЭР (reason='purchase', ref='PO:<id>:<мөр>').
--   Давхар нэмэхээс сэргийлэх ГАНЦ баталгаа — `lines[].rcv` бол толь, дэвтэр бол үнэн.
-- ⛔ Хатуу устгал БАЙХГҮЙ (delete эрх зориуд олгоогүй). Алдааг цуцлалт/татгалзалтаар.
-- ⚠ `status` өөрчлөлт нь оптимист түгжээтэй (PATCH ?status=eq.<өмнөх>) — хоёр хүн
--   нэгэн зэрэг батлахад нэг нь л хүчинтэй.
--
-- ГАРААР ажиллуулна (db/README.md): идемпотент.
-- ═══════════════════════════════════════════════════════════════════════════

create table if not exists purchases (
  id          text primary key,
  no          bigint generated by default as identity,      -- харагдах дугаар (#12)
  status      text not null default 'request',
  supplier    text not null default '',
  platform    text not null default '',                     -- Taobao | 1688 | бусад
  url         text not null default '',
  fx          numeric not null default 540,                 -- ₮ нэг ¥-д; 1 = ₮-өөр үнэлсэн
  total_mnt   numeric not null default 0,                   -- бараа + хүргэлт/карго
  paid_mnt    numeric,                                      -- бодитоор шилжүүлсэн дүн
  need_by     date,                                         -- хямдрал/эцсийн хугацаа
  note        text not null default '',
  lines       jsonb not null default '[]'::jsonb,
  files       jsonb not null default '[]'::jsonb,           -- хавсаргасан файлын URL-ууд
  history     jsonb not null default '[]'::jsonb,           -- [{at, by, to, note}] append-only
  import_key  text,                                         -- Excel-ээс оруулахад давхардлаас хамгаална
  created_by  text not null default '',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create unique index if not exists purchases_import_key_uniq
  on purchases (import_key) where import_key is not null;
create index if not exists purchases_status_idx on purchases (status);
create index if not exists purchases_created_idx on purchases (created_at desc);

-- Эрх: аппын `canSeePurchases()`-ийн толь = CEO ∪ санхүүг бүтнээр харах ∪
-- ил олгосон `purchases` цэс ∪ `products.edit`. (DB нь аппаас ЧАНГА байж болохгүй.)
alter table purchases enable row level security;
drop policy if exists purchases_rw on purchases;
create policy purchases_rw on purchases for all to authenticated
  using      (sec.is_ceo() or sec.fin_full() or sec.can('purchases') or sec.can('products.edit'))
  with check (sec.is_ceo() or sec.fin_full() or sec.can('purchases') or sec.can('products.edit'));

-- anon-д ОГТ нээхгүй (нийлүүлэгч, үнэ = дотоод мэдээлэл).
revoke all on purchases from anon;
grant select, insert, update on purchases to authenticated;
-- ⛔ DELETE ИЛ ХУРААНА — эзний DEFAULT PRIVILEGES шинэ хүснэгт бүрд `arwd` олгодог.
revoke delete on purchases from authenticated;

notify pgrst, 'reload schema';
